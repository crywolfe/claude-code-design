#!/usr/bin/env bash
# Self-test for the plugin's PreToolUse guards. Run from anywhere:
#   bash "${CLAUDE_PLUGIN_ROOT}"/hooks/test-guard.sh
# Prints one PASS/FAIL line per case and exits 1 on any failure.
# The bash guard allows exactly this invocation and nothing else for `bash`.
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
HOOK="$here/guard-bash.sh"
BHOOK="$here/guard-browser.py"
export CLAUDE_PROJECT_DIR="/Users/gw/proj"
fail=0; n=0

check() {
  local expect="$1" cmd="$2" json out rc
  n=$((n + 1))
  json="$(python3 -c 'import json,sys; print(json.dumps({"tool_name":"Bash","tool_input":{"command":sys.argv[1]}}))' "$cmd")"
  out="$(printf '%s' "$json" | bash "$HOOK" 2>&1)"; rc=$?
  if [[ "$expect" == allow && $rc -eq 0 ]] || [[ "$expect" == block && $rc -eq 2 ]]; then
    printf 'PASS %-5s  %s\n' "$expect" "$cmd"
  else
    printf 'FAIL %-5s rc=%s  %s   [%s]\n' "$expect" "$rc" "$cmd" "$out"; fail=1; fails+=("$expect  $cmd")
  fi
}

# browser guard: bcheck <allow|block> <tool_name> '<tool_input json>'
bcheck() {
  local expect="$1" tool="$2" input="$3" out rc
  n=$((n + 1))
  out="$(printf '{"tool_name":"%s","tool_input":%s}' "$tool" "$input" | python3 "$BHOOK" 2>&1)"; rc=$?
  if [[ "$expect" == allow && $rc -eq 0 ]] || [[ "$expect" == block && $rc -eq 2 ]]; then
    printf 'PASS %-5s  %s %s\n' "$expect" "$tool" "$input"
  else
    printf 'FAIL %-5s rc=%s  %s %s   [%s]\n' "$expect" "$rc" "$tool" "$input" "$out"; fail=1; fails+=("$expect  $tool $input")
  fi
}
